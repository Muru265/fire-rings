"""Muru item 1: did S-NPP degrade in its final months? Compare S-NPP with NOAA-20, NOAA-21 and MODIS (Aug–Oct 2026),
each scaled to MODIS-equivalent with its own ratio, and compare the S-NPP/NOAA-20 ratio with its own history per month.

k   = MODIS/S-NPP per month (from calib_{region}.json, method used)
k′  = S-NPP/NOAA-20 per month (same file)
k″  = S-NPP/NOAA-21, ratio of sums per calendar month over Mar 2023 – Jul 2026 (computed here, same estimator)
Writes data/out/snpp_endcheck.json and docs/snpp_endcheck.md.
"""
import json
import sys
from pathlib import Path

import numpy as np
import polars as pl

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from lib.common import ROOT, config, path, read_json, write_json  # noqa: E402

MON = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"]


def cube(region):
    m = pl.read_parquet(path("cube") / f"{region}_monthly.parquet")
    return {(r["y"], r["m"], r["stream"]): (np.nan if r["flag"] or r["C_adj"] is None else r["C_adj"]) for r in m.iter_rows(named=True)}


def main():
    out, lines = {}, ["# S-NPP end-of-life check (Aug–Oct 2026)", "",
                      "Generated by `python pipeline/tools/snpp_endcheck.py`. MODIS-equivalent fire-days per month from each VIIRS",
                      "satellite scaled by its own ratio (k·S-NPP, k·k′·NOAA-20, k·k″·NOAA-21), plus raw MODIS (drifting orbit, for reference).",
                      "Second table: S-NPP ÷ NOAA-20 in 2026 vs the same calendar month in 2018–2025 (min–max of yearly ratios).", ""]
    for region in ["punjab", "madagascar", "se_australia"]:
        c = cube(region)
        v = read_json(path("out") / f"validation_{region}.json")["summary"]["method"]
        cal = read_json(path("out") / f"calib_{region}.json")["methods"][v]
        k, kp = np.array(cal["k"]["month"]), np.array(cal["kprime"]["month"])
        # k'' S-NPP/N21 over Mar 2023 – Jul 2026 per month
        kpp = []
        for m in range(1, 13):
            a = b = 0.0
            for y in range(2023, 2027):
                if (y, m) < (2023, 3) or (y, m) > (2026, 7):
                    continue
                s, n = c.get((y, m, "SNPP"), np.nan), c.get((y, m, "N21"), np.nan)
                if not (np.isnan(s) or np.isnan(n)):
                    a, b = a + s, b + n
            kpp.append((a + 0.5) / (b + 0.5))
        rows, hist = [], []
        for m in (8, 9, 10):
            s, n20, n21, mo = (c.get((2026, m, x), np.nan) for x in ("SNPP", "N20", "N21", "MODIS"))
            e = {"month": f"{MON[m-1]} 2026", "snpp_H": k[m-1] * s, "n20_H": k[m-1] * kp[m-1] * n20,
                 "n21_H": k[m-1] * kpp[m-1] * n21, "modis_raw": mo}
            e["snpp_vs_n20_pct"] = 100 * (e["snpp_H"] / e["n20_H"] - 1) if e["n20_H"] else None
            e["snpp_vs_n21_pct"] = 100 * (e["snpp_H"] / e["n21_H"] - 1) if e["n21_H"] else None
            rows.append(e)
            yr = [c[(y, m, "SNPP")] / c[(y, m, "N20")] for y in range(2018, 2026)
                  if not np.isnan(c.get((y, m, "SNPP"), np.nan)) and c.get((y, m, "N20"), 0) > 0]
            hist.append({"month": MON[m-1], "ratio_2026": s / n20 if n20 else None,
                         "hist_min": min(yr) if yr else None, "hist_max": max(yr) if yr else None, "k_prime": kp[m-1]})
        out[region] = {"rows": rows, "ratio_history": hist}
        lines += [f"## {region}", "", "| month | k·S-NPP | k·k′·NOAA-20 | k·k″·NOAA-21 | S-NPP vs N20 | S-NPP vs N21 | MODIS raw |",
                  "|---|---:|---:|---:|---:|---:|---:|"]
        for e in rows:
            lines.append(f"| {e['month']} | {e['snpp_H']:.0f} | {e['n20_H']:.0f} | {e['n21_H']:.0f} | {e['snpp_vs_n20_pct']:+.1f}% | "
                         f"{e['snpp_vs_n21_pct']:+.1f}% | {e['modis_raw']:.0f} |")
        lines += ["", "| month | S-NPP÷NOAA-20 2026 | 2018–2025 range | k′ (S-NPP/N20, used) |", "|---|---:|---:|---:|"]
        for h in hist:
            lines.append(f"| {h['month']} | {h['ratio_2026']:.3f} | {h['hist_min']:.3f}–{h['hist_max']:.3f} | {h['k_prime']:.3f} |")
        lines.append("")
    write_json(path("out") / "snpp_endcheck.json", out)
    (ROOT / "docs" / "snpp_endcheck.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
