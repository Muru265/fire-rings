"""Write docs/pipeline_report.md from data/out/unify_*.json and mask_*.json (rows per region × stream × step)."""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from lib.common import ROOT, config, path, read_json  # noqa: E402

STEPS = ["in", "conf", "type", "known", "persist"]
LABEL = {"in": "unified", "conf": "after conf≠L", "type": "after type∉{1,2,3}", "known": "after known-static",
         "persist": "after persistence (= kept)"}


def pct(a: int, b: int) -> str:
    return f"{100 * a / b:.1f}%" if b else "—"


def main() -> None:
    out = path("out")
    L = ["# Pipeline report — rows in/out", "",
         "Generated by `python pipeline/tools/pipeline_report.py` from the JSON logs of 02_unify and 03_mask.", ""]
    t2 = out / "punjab_type2.json"
    if t2.exists():
        j = read_json(t2)
        L += ["## Punjab FIRMS type-2 seasonality check (review item 2)", "",
              "| sensor | type-0 rows | type-2 rows | Oct+Nov share type-0 | Oct+Nov share type-2 | ratio |",
              "|---|---:|---:|---:|---:|---:|"]
        for s in ("modis", "snpp"):
            v = j[s]
            L.append(f"| {s} | {v['type0_total']:,} | {v['type2_total']:,} | {v['octnov_share_type0']:.3f} | "
                     f"{v['octnov_share_type2']:.3f} | {v['ratio']} |")
        L += ["", f"Rule: keep type 2 in Punjab only if ratio > 2 for both sensors. **Decision: `{j['decision']}`** — "
              "type 2 does not concentrate in the crop-burning season, so FIRMS type 1/2/3 are dropped as planned.", ""]
    L += ["## Unify (02_unify.py)", "",
          "| region | read (all files) | in clip box | NRT dropped (date covered by archive) | exact duplicates | out | solar-date range |",
          "|---|---:|---:|---:|---:|---:|---|"]
    for region in config()["regions"]:
        u = read_json(out / f"unify_{region}.json")
        L.append(f"| {region} | {sum(u['read'].values()):,} | {u['in_box']:,} | {u['nrt_overlap_dropped']:,} | "
                 f"{u['exact_dup_dropped']:,} | {u['out_total']:,} | {u['date_range'][0]} → {u['date_range'][1]} |")
    L += ["", "## Filters and masks (03_mask.py)", "",
          "Rows remaining after each step, per stream and product. Steps are cumulative and identical for both sensors.", ""]
    nrt_rows = []
    for region in config()["regions"]:
        m = read_json(out / f"mask_{region}.json")
        c = m["cells"]
        L += [f"### {region}", "",
              f"Masked H3 r9 cells: known-static {c['known']:,} · persistence {c['persist']:,} "
              f"(of which also known-static: {c['persist_also_known']:,})", "",
              "| stream/product | " + " | ".join(LABEL[s] for s in STEPS) + " | kept share |",
              "|---|" + "---:|" * (len(STEPS) + 1)]
        tot = {s: 0 for s in STEPS}
        for key, v in m["steps"].items():
            L.append(f"| {key} | " + " | ".join(f"{v[s]:,}" for s in STEPS) + f" | {pct(v['persist'], v['in'])} |")
            for s in STEPS:
                tot[s] += v[s]
            if key.endswith("/NRT"):
                nrt_rows.append((region, key, v["in"], v["type"] - v["known"], v["type"] - v["persist"]))
        L += ["| **total** | " + " | ".join(f"**{tot[s]:,}**" for s in STEPS) + f" | {pct(tot['persist'], tot['in'])} |", ""]
    L += ["## NRT rows removed by the known-static mask (review item 1)", "",
          "NRT files carry no `type` column, so these rows could only be caught by the archive-derived known-static mask.", "",
          "| region | stream | NRT rows in | removed by known-static | removed by known-static + persistence |",
          "|---|---|---:|---:|---:|"]
    for region, key, n_in, rm_known, rm_all in nrt_rows:
        L.append(f"| {region} | {key.split('/')[0]} | {n_in:,} | {rm_known:,} | {rm_all:,} |")
    by_region: dict = {}
    for region, _, n_in, rm_known, _ in nrt_rows:
        a = by_region.setdefault(region, [0, 0])
        a[0] += n_in
        a[1] += rm_known
    L += ["", "| region | NRT rows in (all streams) | removed by known-static | share |", "|---|---:|---:|---:|"]
    for region, (n_in, rm) in by_region.items():
        L.append(f"| {region} | {n_in:,} | {rm:,} | {pct(rm, n_in)} |")
    (ROOT / "docs" / "pipeline_report.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("wrote docs/pipeline_report.md")


if __name__ == "__main__":
    main()
