"""Inventory every raw FIRMS CSV with DuckDB (single aggregate pass per file, no full load).

Writes docs/data_inventory.md and data/out/data_inventory.json.
Usage: python pipeline/00_inventory.py
"""
from __future__ import annotations

import json
import time
from pathlib import Path

import duckdb

ROOT = Path(__file__).resolve().parents[1]
RAW = ROOT / "data" / "raw"
DOC = ROOT / "docs" / "data_inventory.md"
OUT_JSON = ROOT / "data" / "out" / "data_inventory.json"


def header(path: Path) -> list[str]:
    with path.open("r", encoding="utf-8") as fh:
        return fh.readline().strip().split(",")


def inspect(con: duckdb.DuckDBPyConnection, path: Path) -> dict:
    cols = header(path)
    has_type = "type" in cols
    src = f"read_csv('{path.as_posix()}', all_varchar=true, header=true)"
    type_expr = "string_agg(DISTINCT type, ',' ORDER BY type)" if has_type else "NULL"
    row = con.execute(
        f"""
        SELECT count(*) AS rows,
               min(acq_date) AS dmin, max(acq_date) AS dmax,
               string_agg(DISTINCT satellite, ',' ORDER BY satellite) AS sats,
               string_agg(DISTINCT instrument, ',' ORDER BY instrument) AS instr,
               string_agg(DISTINCT version, ',' ORDER BY version) AS vers,
               string_agg(DISTINCT daynight, ',' ORDER BY daynight) AS dn,
               {type_expr} AS types,
               count(DISTINCT confidence) AS n_conf,
               min(TRY_CAST(confidence AS INTEGER)) AS conf_min_num,
               max(TRY_CAST(confidence AS INTEGER)) AS conf_max_num,
               count(*) FILTER (WHERE TRY_CAST(confidence AS INTEGER) IS NULL) AS conf_non_numeric,
               min(TRY_CAST(latitude AS DOUBLE)) AS lat_min, max(TRY_CAST(latitude AS DOUBLE)) AS lat_max,
               min(TRY_CAST(longitude AS DOUBLE)) AS lon_min, max(TRY_CAST(longitude AS DOUBLE)) AS lon_max,
               min(length(acq_time)) AS t_len_min, max(length(acq_time)) AS t_len_max,
               count(*) FILTER (WHERE TRY_CAST(frp AS DOUBLE) IS NULL) AS frp_null
        FROM {src}
        """
    ).fetchone()
    names = ["rows", "dmin", "dmax", "sats", "instr", "vers", "dn", "types", "n_conf",
             "conf_min_num", "conf_max_num", "conf_non_numeric", "lat_min", "lat_max",
             "lon_min", "lon_max", "t_len_min", "t_len_max", "frp_null"]
    rec = dict(zip(names, row))
    # confidence format: categorical (VIIRS l/n/h) vs numeric (MODIS 0-100)
    if rec["conf_non_numeric"] == 0:
        rec["conf_format"] = f"numeric {rec['conf_min_num']}–{rec['conf_max_num']}"
    else:
        vals = con.execute(
            f"SELECT confidence, count(*) FROM {src} GROUP BY 1 ORDER BY 1"
        ).fetchall()
        rec["conf_format"] = " ".join(f"{v}:{n}" for v, n in vals)
    parts = path.relative_to(RAW).parts
    rec.update(region=parts[0], sensor=parts[1],
               product="archive" if path.name.startswith("fire_archive") else "nrt",
               file=path.name, size_mb=round(path.stat().st_size / 1e6, 1), header=cols)
    return rec


def main() -> None:
    files = sorted(RAW.glob("*/*/fire_*.csv"))
    con = duckdb.connect()
    con.execute("SET threads TO 8")
    recs = []
    for f in files:
        t0 = time.time()
        r = inspect(con, f)
        print(f"{r['region']:<11} {r['sensor']:<7} {r['product']:<7} rows={r['rows']:>10,} "
              f"{r['dmin']}→{r['dmax']}  sats={r['sats']}  ({time.time()-t0:.1f}s)", flush=True)
        recs.append(r)
    OUT_JSON.parent.mkdir(parents=True, exist_ok=True)
    OUT_JSON.write_text(json.dumps(recs, indent=1, default=str))
    write_md(recs)


def write_md(recs: list[dict]) -> None:
    L = ["# Raw data inventory", "",
         "Generated by `python pipeline/00_inventory.py` (DuckDB aggregate scan, all columns read as text).",
         "Source: NASA FIRMS Archive Download, delivered 2026-11-09.", "",
         "## Summary", "",
         "| region | sensor | product | rows | min date | max date | satellite | instrument | version | confidence | type | day/night | MB |",
         "|---|---|---|---:|---|---|---|---|---|---|---|---|---:|"]
    for r in recs:
        L.append(f"| {r['region']} | {r['sensor']} | {r['product']} | {r['rows']:,} | {r['dmin']} | {r['dmax']} | "
                 f"{r['sats']} | {r['instr']} | {r['vers']} | {r['conf_format']} | {r['types'] or '— (no column)'} | "
                 f"{r['dn']} | {r['size_mb']} |")
    L += ["", "## Extents and field checks", "",
          "| region | sensor | product | lat range | lon range | acq_time length | frp non-numeric |",
          "|---|---|---|---|---|---|---:|"]
    for r in recs:
        L.append(f"| {r['region']} | {r['sensor']} | {r['product']} | {r['lat_min']:.3f} → {r['lat_max']:.3f} | "
                 f"{r['lon_min']:.3f} → {r['lon_max']:.3f} | {r['t_len_min']}–{r['t_len_max']} | {r['frp_null']} |")
    L += ["", "## Headers", ""]
    seen: dict[str, list[str]] = {}
    for r in recs:
        seen.setdefault(",".join(r["header"]), []).append(f"{r['region']}/{r['sensor']}/{r['product']}")
    for h, where in seen.items():
        L += [f"- `{h}`", f"  - {len(where)} files: {', '.join(where)}"]
    L += ["", NOTES]
    DOC.write_text("\n".join(L), encoding="utf-8")


