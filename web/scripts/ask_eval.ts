// Run 30 test questions through the Ask core and check every number against tool results.
// Usage: npx tsx --env-file=../.env scripts/ask_eval.ts   → ../docs/ask_eval.md
import { writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { allowedNumbers, ask, unverified } from '../api/_lib/core.js'
import type { AskResult, Voice } from '../api/_lib/core.js'
import { apiKey, load, models, sleep } from './ask_local.js'

const Q: [string, string | undefined, Voice][] = [
  ['Is this month unusual?', 'punjab', 'responder'],
  ['Worst year on record?', 'punjab', 'responder'],
  ['When does the season peak?', 'punjab', 'responder'],
  ['How reliable is this?', 'punjab', 'scientist'],
  ['How did October 2026 compare with a normal October in Punjab?', undefined, 'responder'],
  ['Was November 2016 a big crop-burning month in Punjab?', undefined, 'scientist'],
  ['Which years look most like this year in Punjab?', undefined, 'responder'],
  ['Is this month unusual?', 'madagascar', 'responder'],
  ['Worst year on record?', 'madagascar', 'scientist'],
  ['When does the season peak?', 'madagascar', 'responder'],
  ['How reliable is this?', 'madagascar', 'responder'],
  ['How bad was September 2019 in Madagascar?', undefined, 'scientist'],
  ['What is the quietest month in Madagascar?', undefined, 'responder'],
  ['Is this month unusual?', 'se_australia', 'responder'],
  ['How did Black Summer rank?', 'se_australia', 'scientist'],
  ['When does the season peak?', 'se_australia', 'responder'],
  ['How reliable is this?', 'se_australia', 'scientist'],
  ['What happened in December 2019 in SE Australia?', undefined, 'responder'],
  ['Is this month unusual?', 'mauritius', 'responder'],
  ['Worst year on record?', 'mauritius', 'responder'],
  ['How reliable is this?', 'mauritius', 'scientist'],
  ['When does the season peak?', 'mauritius', 'responder'],
  ['Which regions can I ask about?', undefined, 'responder'],
  ['How many fires will there be next month in Punjab?', undefined, 'responder'],
  ['What about fires in California?', undefined, 'responder'],
  ['Compare this October with last October in Punjab.', undefined, 'scientist'],
  ['Is the data for November 2026 final?', 'punjab', 'responder'],
  ['What were the three lowest years in Madagascar?', undefined, 'responder'],
  ['Explain the 2012 jump in the raw data for Punjab.', undefined, 'scientist'],
  ['Rank Septembers in Madagascar.', undefined, 'responder'],
]

const rows: string[] = []
let invented = 0
let errors = 0
let withheld = 0
for (const [i, [q, region, voice]] of Q.entries()) {
  let out: AskResult | null = null
  let err = ''
  for (let attempt = 0; attempt < 3 && !out; attempt++) {
    try { out = await ask({ apiKey: apiKey(), models, load, question: q, voice, region }) } catch (e) { err = (e as Error).message.slice(0, 160); await sleep(4000) }
  }
  if (!out) { errors++; rows.push(`| ${i + 1} | ${q} | ${region ?? '—'} | ${voice} | ERROR | — | ${err.replace(/\|/g, '/')} |`); console.log(i + 1, 'ERROR', err); continue }
  const bad = unverified(`${out.answer} ${out.caveat}`, allowedNumbers(out.trace, q))
  if (bad.length) invented++
  if (!out.verified) withheld++
  const tools = out.trace.map((t) => t.tool).join(', ') || '(none)'
  const ans = `${out.answer} _Caveat: ${out.caveat}_`.replace(/\|/g, '/').replace(/\n/g, ' ')
  rows.push(`| ${i + 1} | ${q} | ${region ?? '—'} | ${voice} | ${bad.length ? `❌ ${bad.join(', ')}` : out.verified ? '✅' : '⚠️ withheld'} | ${tools} | ${ans} |`)
  console.log(i + 1, bad.length ? `INVENTED ${bad}` : out.verified ? 'ok' : 'withheld', out.model, tools)
  await sleep(1500)
}
const md = `# Ask Fire Rings — 30-question evaluation

Generated by \`npx tsx --env-file=../.env scripts/ask_eval.ts\` on ${new Date().toISOString().slice(0, 16)}Z.
Check: every number in the answer and caveat must appear in a tool result of that conversation (or in the question).
The server runs the same check and does one correction round; answers that still fail are withheld.

**Result: ${Q.length - errors}/${Q.length} answered · ${invented} with numbers not in tool results · ${withheld} withheld · ${errors} errors.**

| # | Question | Region ctx | Voice | Numbers | Tools | Answer |
|---:|---|---|---|---|---|---|
${rows.join('\n')}
`
const here = dirname(fileURLToPath(import.meta.url))
await writeFile(resolve(here, '../../docs/ask_eval.md'), md, 'utf-8')
console.log(`\nanswered ${Q.length - errors}/${Q.length}, invented ${invented}, withheld ${withheld}, errors ${errors}`)
