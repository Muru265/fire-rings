// GET /api/hotspots?region=punjab|bbox=W,S,E,N&start=YYYY-MM-DD&end=YYYY-MM-DD[&satellites=record|all][&format=csv|json]
// Filtered NASA FIRMS detections (MODIS + VIIRS) for any search of ≤31 days, same filters as the record (see _lib/hotspots.ts).
// Caching: same query → no new NASA call (in-memory per warm instance + CDN cache headers; archived ranges cached 7 days).
// Pre-saved demo months are served from static files, so the demo never depends on NASA being reachable.
// Throttle: ≤300 FIRMS calls per 10 min per instance (key limit 5,000 transactions / 10 min, shared with /api/live).
import { readFile } from 'node:fs/promises'
import { join } from 'node:path'
import { cacheKey, chunkRange, fetchHotspots, FALLBACK_AVAIL, InputError, parseQuery, toCsv, toDownloadCsv, toJson } from './_lib/hotspots.js'
import type { LiveFile, Query } from './_lib/hotspots.js'

const REGIONS: Record<string, string> = { punjab: 'Punjab–Haryana', madagascar: 'Madagascar', se_australia: 'SE Australia (NSW + VIC)', mauritius: 'Mauritius (incl. Rodrigues)', nt_savanna: 'Northern Australia savanna (NT)', ne_india: 'Northeast India', tanzania: 'Tanzania', sudan: 'Sudan', mato_grosso: 'Mato Grosso, Brazil' }
const CORS = { 'access-control-allow-origin': '*', 'access-control-allow-methods': 'GET, OPTIONS', 'access-control-expose-headers': 'x-fire-rings-cache, x-fire-rings-rows, x-fire-rings-truncated' }
const BUSY = 'NASA’s data service is busy — try again in a few minutes; hexagons still work.'
const MAX_BYTES = 4_200_000 // Vercel function response limit is 4.5 MB

const cache = new Map<string, { t: number; ttl: number; body: string; type: string; rows: number; truncated?: string }>()
const calls: number[] = []
const hits = new Map<string, number[]>()
let avail: { t: number; v: Record<string, [string, string]> } | null = null

function limited(ip: string): boolean {
  const now = Date.now()
  const arr = (hits.get(ip) ?? []).filter((t) => now - t < 600_000)
  arr.push(now)
  hits.set(ip, arr)
  return arr.length > 30 // uncached requests per IP per 10 min
}
const callBudget = () => { const now = Date.now(); while (calls.length && now - calls[0] > 600_000) calls.shift(); return 300 - calls.length }

async function readJson<T>(rel: string, origin: string): Promise<T | null> {
  for (const base of [join(process.cwd(), 'public', 'data', 'v1'), join(process.cwd(), 'web', 'public', 'data', 'v1')]) {
    try { return JSON.parse(await readFile(join(base, rel), 'utf-8')) } catch { /* next */ }
  }
  try { const r = await fetch(`${origin}/data/v1/${rel}`, { signal: AbortSignal.timeout(4000) }); return r.ok ? r.json() : null } catch { return null }
}

async function availability(key: string): Promise<Record<string, [string, string]>> {
  if (avail && Date.now() - avail.t < 6 * 3600_000) return avail.v
  try {
    calls.push(Date.now())
    const r = await fetch(`https://firms.modaps.eosdis.nasa.gov/api/data_availability/csv/${key}/all`, { signal: AbortSignal.timeout(6000) })
    const v: Record<string, [string, string]> = {}
    for (const l of (await r.text()).trim().split(/\r?\n/).slice(1)) { const [id, a, b] = l.split(','); if (/^\d{4}-\d\d-\d\d$/.test(a ?? '')) v[id] = [a, b] }
    if (v.MODIS_SP) { avail = { t: Date.now(), v }; return v }
  } catch { /* fallback */ }
  return FALLBACK_AVAIL
}

const json = (body: unknown, status = 200, extra: Record<string, string> = {}) =>
  Response.json(body, { status, headers: { ...CORS, 'cache-control': 'no-store', ...extra } })

export function OPTIONS(): Response { return new Response(null, { status: 204, headers: CORS }) }

export async function GET(req: Request): Promise<Response> {
  const url = new URL(req.url)
  let q: Query
  try { q = parseQuery(url.searchParams, Object.keys(REGIONS)) } catch (e) {
    if (e instanceof InputError) return json({ ok: false, error: e.code, message: e.message }, 400)
    throw e
  }
  const name = q.region ? REGIONS[q.region] : null
  const filename = `fire-rings_hotspots_${q.region ?? 'box'}_${q.start}_to_${q.end}.${q.format}`
  const disp = { 'content-disposition': `${q.format === 'csv' ? 'attachment' : 'inline'}; filename="${filename}"` }

  // 1) pre-saved demo months (static, generated by the pipeline from the record itself)
  if (q.region && !q.bbox && q.satellites === 'record' && q.layout !== 'download') {
    const idx = await readJson<{ files: { region: string; month: string; start: string; end: string; csv: string; json: string }[] }>('hotspots/demo/index.json', url.origin)
    const d = idx?.files.find((f) => f.region === q.region && f.start === q.start && f.end === q.end)
    if (d) return new Response(null, { status: 307, headers: { ...CORS, location: `/data/v1/hotspots/demo/${q.format === 'csv' ? d.csv : d.json}`, 'x-fire-rings-cache': 'static-demo', 'cache-control': 'public, max-age=3600' } })
  }
  // 2) cache
  const k = cacheKey(q)
  const hit = cache.get(k)
  if (hit && Date.now() - hit.t < hit.ttl) {
    return new Response(hit.body, { headers: { ...CORS, ...disp, 'content-type': hit.type, 'x-fire-rings-cache': 'hit', 'x-fire-rings-rows': String(hit.rows), ...(hit.truncated ? { 'x-fire-rings-truncated': hit.truncated } : {}), 'cache-control': `public, max-age=300, s-maxage=${Math.round(hit.ttl / 1000)}` } })
  }
  const key = process.env.FIRMS_MAP_KEY
  if (!key) return json({ ok: false, error: 'not_configured', message: 'The hotspot service is not configured on this server.' }, 503)
  const ip = (req.headers.get('x-forwarded-for') ?? 'unknown').split(',')[0].trim()
  if (limited(ip)) return json({ ok: false, error: 'rate_limited', message: 'Too many downloads from your address — please wait a few minutes.' }, 429, { 'retry-after': '300' })
  if (callBudget() < 20) return json({ ok: false, error: 'busy', message: BUSY }, 503, { 'retry-after': '300' })

  const files: LiveFile[] = []
  for (const r of q.region ? [q.region] : Object.keys(REGIONS)) {
    const f = await readJson<LiveFile>(`live/${r}.json`, url.origin)
    if (!f) continue
    // free box: only masks of regions whose box overlaps it
    if (!q.region && q.bbox && (f.bbox[0] > q.bbox[2] || f.bbox[2] < q.bbox[0] || f.bbox[1] > q.bbox[3] || f.bbox[3] < q.bbox[1])) continue
    files.push(f)
  }
  if (q.region && !files.length) return json({ ok: false, error: 'unavailable', message: 'Region files not found on the server.' }, 500)
  const av = await availability(key)
  if (q.layout === 'download') return download(q, name, files, av, key, k, disp)
  const res = await fetchHotspots({ key, q, files, avail: av, onCall: () => calls.push(Date.now()), timeoutMs: 50_000 })
  if (!res.ok) {
    if (res.busy) return json({ ok: false, error: 'busy', message: BUSY, sources: res.sources }, 503, { 'retry-after': '300' })
    return json({ ok: false, error: 'firms_error', message: res.error ?? 'NASA FIRMS error', sources: res.sources }, 502)
  }
  const body = q.format === 'csv' ? toCsv(res, name) : JSON.stringify(toJson(res))
  if (body.length > MAX_BYTES)
    return json({ ok: false, error: 'too_large', count: res.rows.length, message: `${res.rows.length.toLocaleString('en-GB')} detections — too many for one download. Choose fewer days or a smaller box.` }, 413)
  // archived (SP-only) ranges never change → cache a week; ranges touching NRT → 30 min
  const archived = Object.keys(res.sources).every((s) => s.endsWith('_SP'))
  const ttl = archived ? 7 * 86_400_000 : 30 * 60_000
  const type = q.format === 'csv' ? 'text/csv; charset=utf-8' : 'application/json'
  cache.set(k, { t: Date.now(), ttl, body, type, rows: res.rows.length })
  if (cache.size > 200) cache.delete(cache.keys().next().value!)
  return new Response(body, { headers: { ...CORS, ...disp, 'content-type': type, 'x-fire-rings-cache': 'miss', 'x-fire-rings-rows': String(res.rows.length), 'cache-control': `public, max-age=300, s-maxage=${Math.round(ttl / 1000)}` } })
}

/** Round 8: Explore "Download hotspots (CSV)". Chunks of ≤31 days, one after another inside a 50 s budget; whatever could
 *  not be fetched is reported in the CSV's first line and the x-fire-rings-truncated header — never silently dropped. */
async function download(q: Query, name: string | null, files: LiveFile[], av: Record<string, [string, string]>, key: string, k: string,
  disp: Record<string, string>): Promise<Response> {
  const deadline = Date.now() + 50_000
  const pieces = chunkRange(q.start, q.end)
  let merged: Awaited<ReturnType<typeof fetchHotspots>> | null = null
  let coveredEnd: string | null = null
  let truncated: string | null = null
  for (const [a, b] of pieces) {
    const left = deadline - Date.now()
    if (left < 8_000) { truncated = `time limit reached; data cover ${q.start} to ${coveredEnd ?? q.start} only — request ${a} to ${q.end} separately`; break }
    const r = await fetchHotspots({ key, q: { ...q, start: a, end: b }, files, avail: av, onCall: () => calls.push(Date.now()), timeoutMs: left - 2_000 })
    if (!r.ok) {
      if (!merged) return r.busy ? json({ ok: false, error: 'busy', message: BUSY }, 503, { 'retry-after': '300' }) : json({ ok: false, error: 'firms_error', message: r.error ?? 'NASA FIRMS error' }, 502)
      truncated = `NASA FIRMS ${r.busy ? 'was busy' : 'returned an error'} for ${a} to ${b}; data cover ${q.start} to ${coveredEnd} only — try the rest again later`
      break
    }
    if (!merged) merged = { ...r, query: { ...q } }
    else { merged.rows.push(...r.rows); for (const [s, v] of Object.entries(r.sources)) { const m = (merged.sources[s] ??= { calls: 0, rows: 0, kept: 0 }); m.calls += v.calls; m.rows += v.rows; m.kept += v.kept } }
    coveredEnd = b
  }
  const out = toDownloadCsv(merged!, name, { requested: [q.start, q.end], covered: coveredEnd ? [q.start, coveredEnd] : null, truncated }, MAX_BYTES)
  const archived = Object.keys(merged!.sources).every((s) => s.endsWith('_SP'))
  const ttl = out.truncated ? 5 * 60_000 : archived ? 7 * 86_400_000 : 30 * 60_000
  const type = 'text/csv; charset=utf-8'
  cache.set(k, { t: Date.now(), ttl, body: out.body, type, rows: out.rows, ...(out.truncated ? { truncated: 'yes' } : {}) })
  return new Response(out.body, { headers: { ...CORS, ...disp, 'content-type': type, 'x-fire-rings-cache': 'miss', 'x-fire-rings-rows': String(out.rows),
    ...(out.truncated ? { 'x-fire-rings-truncated': 'yes' } : {}), 'cache-control': `public, max-age=300, s-maxage=${Math.round(ttl / 1000)}` } })
}
